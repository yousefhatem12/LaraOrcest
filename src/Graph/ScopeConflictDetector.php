<?php

declare(strict_types=1);

namespace Yousef\LaraOrcest\Graph;

class ScopeConflictDetector
{
    /**
     * Normalizes a filesystem or resource path for deterministic comparison.
     */
    public static function normalizePath(string $path): string
    {
        $normalized = str_replace('\\', '/', trim($path));
        // Remove redundant multiple slashes
        $normalized = (string) preg_replace('#/+#', '/', $normalized);
        // Remove leading ./
        if (str_starts_with($normalized, './')) {
            $normalized = substr($normalized, 2);
        }

        return trim($normalized, '/');
    }

    /**
     * Normalizes an array of scope paths.
     *
     * @param  array<int, string>  $scopes
     * @return array<int, string>
     */
    public static function normalizeScopes(array $scopes): array
    {
        $result = [];
        foreach ($scopes as $scope) {
            $normalized = self::normalizePath((string) $scope);
            if ($normalized !== '') {
                $result[] = $normalized;
            }
        }

        return array_values(array_unique($result));
    }

    /**
     * Checks if two paths overlap (either identical, one contains the other as directory prefix, or wildcard matches).
     */
    public static function pathsOverlap(string $pathA, string $pathB): bool
    {
        $a = self::normalizePath($pathA);
        $b = self::normalizePath($pathB);

        if ($a === '' || $b === '') {
            return false;
        }

        // Exact match
        if ($a === $b) {
            return true;
        }

        // Check if one contains wildcard
        if (str_contains($a, '*') || str_contains($b, '*')) {
            if (fnmatch($a, $b) || fnmatch($b, $a)) {
                return true;
            }
        }

        // Directory containment:
        // 'app/Models' contains 'app/Models/User.php'
        if (str_starts_with($b, $a . '/')) {
            return true;
        }

        if (str_starts_with($a, $b . '/')) {
            return true;
        }

        return false;
    }

    /**
     * Determines whether two sets of scope paths have any overlapping paths.
     *
     * @param  array<int, string>  $scopeA
     * @param  array<int, string>  $scopeB
     */
    public static function hasConflict(array $scopeA, array $scopeB): bool
    {
        return ! empty(self::findConflictingPaths($scopeA, $scopeB));
    }

    /**
     * Returns all pairs of conflicting paths between two scope sets.
     *
     * @param  array<int, string>  $scopeA
     * @param  array<int, string>  $scopeB
     * @return array<int, array{path_a: string, path_b: string}>
     */
    public static function findConflictingPaths(array $scopeA, array $scopeB): array
    {
        $normA = self::normalizeScopes($scopeA);
        $normB = self::normalizeScopes($scopeB);

        $conflicts = [];

        foreach ($normA as $pA) {
            foreach ($normB as $pB) {
                if (self::pathsOverlap($pA, $pB)) {
                    $conflicts[] = [
                        'path_a' => $pA,
                        'path_b' => $pB,
                    ];
                }
            }
        }

        return $conflicts;
    }

    /**
     * Inspects artifacts generated by multiple parallel branches to detect colliding file mutations.
     *
     * @param  array<string, array<int, array{path: string, action?: string, summary?: string, timestamp?: string}>>  $branchArtifacts
     * @return array<string, array<int, array{branch: string, action: string, summary: string}>>
     */
    public static function findCollidingArtifacts(array $branchArtifacts): array
    {
        $pathToBranches = [];

        foreach ($branchArtifacts as $branchKey => $artifacts) {
            foreach ($artifacts as $artifact) {
                $rawPath = (string) ($artifact['path'] ?? '');
                $path = self::normalizePath($rawPath);
                if ($path === '') {
                    continue;
                }

                $pathToBranches[$path][] = [
                    'branch' => (string) $branchKey,
                    'action' => (string) ($artifact['action'] ?? 'modified'),
                    'summary' => (string) ($artifact['summary'] ?? ''),
                ];
            }
        }

        // Also check directory/containment collisions across branches
        $conflicts = [];

        // Exact path collisions (more than 1 distinct branch touched the path)
        foreach ($pathToBranches as $path => $entries) {
            $branches = array_unique(array_column($entries, 'branch'));
            if (count($branches) > 1) {
                $conflicts[$path] = $entries;
            }
        }

        // Hierarchical path collisions across branches
        $allPaths = array_keys($pathToBranches);
        $pathCount = count($allPaths);

        for ($i = 0; $i < $pathCount; $i++) {
            for ($j = $i + 1; $j < $pathCount; $j++) {
                $p1 = $allPaths[$i];
                $p2 = $allPaths[$j];

                if ($p1 !== $p2 && self::pathsOverlap($p1, $p2)) {
                    $branches1 = array_unique(array_column($pathToBranches[$p1], 'branch'));
                    $branches2 = array_unique(array_column($pathToBranches[$p2], 'branch'));

                    $diff = array_diff($branches1, $branches2);
                    if (! empty($diff) || count(array_intersect($branches1, $branches2)) !== count($branches1)) {
                        $conflictKey = "{$p1} <-> {$p2}";
                        $conflicts[$conflictKey] = array_merge($pathToBranches[$p1], $pathToBranches[$p2]);
                    }
                }
            }
        }

        return $conflicts;
    }
}
